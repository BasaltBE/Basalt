namespace Basalt.Core.Worlds;

/// <summary>
/// A list of game rules in a dimension.
/// </summary>
public sealed class DimensionGameRules {
    /// <summary>
    /// Whether players can drown in this dimension.
    /// </summary>
    public bool DrowningDamage = true;

    /// <summary>
    /// Whether players take fall damage in this dimension.
    /// </summary>
    public bool FallDamage = true;
}







